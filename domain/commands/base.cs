#nullable enable
using System;
using System.Threading;
using System.Threading.Tasks;

namespace dnd_game.domain.commands
{
    // --------------------------------------------------------------------------------------------
    // Базовые интерфейсы
    // --------------------------------------------------------------------------------------------

    /// <summary>
    /// Маркерный интерфейс для всех команд предметной области.
    /// </summary>
    public interface ICommand
    {
    }

    // --------------------------------------------------------------------------------------------
    // Контекст выполнения (игровая сессия, пользователь)
    // --------------------------------------------------------------------------------------------

    /// <summary>
    /// Команда, несущая контекст выполнения: кто отправил и в рамках какой кампании/сессии.
    /// Позволяет обработчикам и политикам безопасности автоматически извлекать контекст.
    /// </summary>
    public interface IGameCommand : ICommand
    {
        /// <summary>
        /// Идентификатор пользователя (игрока или мастера), инициировавшего команду.
        /// </summary>
        Guid UserId { get; init; }

        /// <summary>
        /// Идентификатор активной игровой сессии (кампании), если применимо.
        /// </summary>
        Guid GameSessionId { get; init; }
    }

    // --------------------------------------------------------------------------------------------
    // Команды, требующие авторизации
    // --------------------------------------------------------------------------------------------

    /// <summary>
    /// Команда, для выполнения которой требуется определённое разрешение.
    /// Обработчик или pipeline безопасности использует это свойство для проверки доступа.
    /// </summary>
    public interface IAuthorizedCommand : IGameCommand
    {
        /// <summary>
        /// Тип требуемого разрешения (например, "EditCharacter", "StartCombat").
        /// </summary>
        string RequiredPermission { get; }
    }

    // --------------------------------------------------------------------------------------------
    // Команды, связанные с конкретным агрегатом
    // --------------------------------------------------------------------------------------------

    /// <summary>
    /// Команда, адресованная конкретному агрегату.
    /// Содержит идентификатор агрегата, позволяя маршрутизировать команду к нужному обработчику
    /// или выполнять предварительную загрузку агрегата.
    /// </summary>
    public interface IAggregateCommand : IGameCommand
    {
        /// <summary>
        /// Идентификатор целевого агрегата.
        /// </summary>
        Guid AggregateId { get; init; }
    }

    // --------------------------------------------------------------------------------------------
    // Идемпотентность
    // --------------------------------------------------------------------------------------------

    /// <summary>
    /// Команда с идентификатором идемпотентности.
    /// Позволяет безопасно повторять отправку при сбоях, не вызывая дублирующих изменений.
    /// </summary>
    public interface IIdempotentCommand : ICommand
    {
        /// <summary>
        /// Уникальный идентификатор запроса, генерируемый клиентом.
        /// </summary>
        Guid IdempotencyKey { get; init; }
    }

    // --------------------------------------------------------------------------------------------
    // Компенсируемые команды (для саг)
    // --------------------------------------------------------------------------------------------

    /// <summary>
    /// Команда, которая может быть отменена через компенсирующее действие.
    /// Используется в длительных процессах (сагах) для реализации отката.
    /// </summary>
    public interface ICompensatableCommand : ICommand
    {
        /// <summary>
        /// Возвращает команду, выполняющую откат (компенсацию) данного действия.
        /// </summary>
        ICommand GetCompensationCommand();
    }

    // --------------------------------------------------------------------------------------------
    // Базовый абстрактный класс команды
    // --------------------------------------------------------------------------------------------

    /// <summary>
    /// Удобный базовый класс для команд, автоматически реализующий общие свойства.
    /// Наследники заполняют только специфичные для команды поля.
    /// </summary>
    public abstract record BaseCommand : IGameCommand, IIdempotentCommand
    {
        /// <inheritdoc/>
        public Guid UserId { get; init; }

        /// <inheritdoc/>
        public Guid GameSessionId { get; init; }

        /// <summary>
        /// Уникальный ключ идемпотентности. По умолчанию генерируется новый GUID,
        /// но клиент может задать его явно для повторных запросов.
        /// </summary>
        public Guid IdempotencyKey { get; init; } = Guid.NewGuid();
    }

    /// <summary>
    /// Базовый класс для команд, адресованных конкретному агрегату.
    /// </summary>
    public abstract record AggregateCommand : BaseCommand, IAggregateCommand
    {
        /// <inheritdoc/>
        public Guid AggregateId { get; init; }
    }

    // --------------------------------------------------------------------------------------------
    // Обработчик команд
    // --------------------------------------------------------------------------------------------

    /// <summary>
    /// Обработчик команд определённого типа. Реализует бизнес-логику, связанную с командой.
    /// </summary>
    /// <typeparam name="TCommand">Тип команды, реализующий <see cref="ICommand"/>.</typeparam>
    public interface ICommandHandler<in TCommand> where TCommand : ICommand
    {
        /// <summary>
        /// Выполняет обработку команды.
        /// </summary>
        /// <param name="command">Команда для обработки.</param>
        /// <param name="cancellationToken">Токен отмены.</param>
        /// <returns>Задача, представляющая асинхронную операцию.</returns>
        Task Handle(TCommand command, CancellationToken cancellationToken = default);
    }
}